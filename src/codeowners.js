'use strict'
const fs = require('node:fs')
const path = require('node:path')
const { toPosix } = require('./files')

const BEGIN = '# BEGIN cds-guard (generated by "cds-guard codeowners", do not edit by hand)'
const END = '# END cds-guard'
const PLATFORMS = ['github', 'gitlab', 'bitbucket', 'azure']
const DEFAULT_FILE = { github: '.github/CODEOWNERS', gitlab: 'CODEOWNERS', bitbucket: '.bitbucket/CODEOWNERS', azure: '.guard/azure-policies.sh' }
// Every place a platform reads CODEOWNERS from; `check` looks for generated blocks in all of them.
const CODEOWNERS_FILES = ['.github/CODEOWNERS', 'CODEOWNERS', 'docs/CODEOWNERS', '.gitlab/CODEOWNERS', '.bitbucket/CODEOWNERS']

/** "alice" -> "@alice"; e-mail addresses and "@team" stay as they are. */
function owner (o) { return o.startsWith('@') || o.includes('@') ? o : '@' + o }

function rooted (p) { return p.startsWith('/') ? p : '/' + p }

/** The generated CODEOWNERS block. `file` is where it goes; the guard owners own that file too. */
function block (config, platform, { file = DEFAULT_FILE[platform] } = {}) {
  const guardOwners = config.guardOwners.map(owner)
  const lines = [BEGIN]
  if (platform === 'gitlab') lines.push('[cds-guard]')
  if (!guardOwners.length) lines.push('# Set "guardOwners" in .guard/protected.yml to protect the guard itself.')
  else {
    lines.push(`/.guard/ ${guardOwners.join(' ')}`)
    const guarded = [...config.guardPaths.map(rooted)]
    if (file && !guarded.includes(rooted(file))) guarded.push(rooted(file))
    for (const g of guarded) lines.push(`${g} ${guardOwners.join(' ')}`)
  }
  for (const r of config.rules) {
    const who = r.approvers.length ? r.approvers.map(owner) : guardOwners
    if (!who.length) { lines.push(`# rule "${r.id}" has no approvers and no guardOwners`); continue }
    lines.push(`/.guard/locks/${r.id}.lock ${who.join(' ')}`)
  }
  lines.push(END)
  return lines.join('\n') + '\n'
}

function shellQuote (s) { return `'${String(s).replace(/'/g, `'\\''`)}'` }

/**
 * Azure DevOps has no CODEOWNERS: emit "az repos policy required-reviewer" commands instead.
 * The script replaces the policies it created before, so it can run again after approvers change.
 */
function azureScript (config, { branch = 'main' } = {}) {
  const lines = [
    '#!/usr/bin/env sh',
    '# Generated by "cds-guard codeowners --platform azure".',
    '# Creates one required-reviewer branch policy per lock file and then removes the policies an',
    '# earlier run created (their message starts with "cds-guard:"). Approvers must be e-mail',
    '# addresses or Azure DevOps group names. Run after "az login" and "az devops configure --defaults ...".',
    'set -e',
    ': "${REPO_ID:?set REPO_ID to the repository id (az repos show --repository NAME --query id -o tsv)}"',
    `BRANCH=\${BRANCH:-${branch}}`,
    'OLD=$(az repos policy list --repository-id "$REPO_ID" --branch "$BRANCH" --query "[?type.displayName==\'Required reviewers\' && settings.message && starts_with(settings.message, \'cds-guard:\')].id" -o tsv)'
  ]
  const add = (filter, who, message) => lines.push(
    `az repos policy required-reviewer create --blocking true --enabled true --branch "$BRANCH" --repository-id "$REPO_ID" --path-filter ${shellQuote(filter)} --required-reviewer-ids ${shellQuote(who.join(';'))} --message ${shellQuote(message)} --output none`
  )
  if (config.guardOwners.length) {
    // Azure policies add up (unlike CODEOWNERS, where the last match wins), so the lock files
    // are left out here: they need only their own rule's approvers.
    add('/.guard/*;!/.guard/locks/*', config.guardOwners, 'cds-guard: guard configuration')
    for (const g of config.guardPaths) add(rooted(g), config.guardOwners, 'cds-guard: guard pipeline')
  }
  for (const r of config.rules) {
    const who = r.approvers.length ? r.approvers : config.guardOwners
    if (who.length) add(`/.guard/locks/${r.id}.lock`, who, `cds-guard: ${r.id}`)
  }
  lines.push('for id in $OLD; do az repos policy delete --id "$id" --yes --output none; done')
  return lines.join('\n') + '\n'
}

/** Replace the generated block in an existing CODEOWNERS file, or append it. */
function writeBlock (file, content) {
  const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''
  const start = existing.indexOf(BEGIN)
  const end = existing.indexOf(END)
  let next
  if (start !== -1 && end > start) next = existing.slice(0, start) + content + existing.slice(end + END.length).replace(/^\r?\n/, '')
  else next = existing + (existing && !existing.endsWith('\n') ? '\n' : '') + (existing ? '\n' : '') + content
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, next)
  return next
}

/**
 * Find the generated approver files in the repository and compare each with what
 * `codeowners` would write now. Returns [{ file, platform, ok, hint }].
 */
function verify (root, config) {
  const found = []
  for (const rel of CODEOWNERS_FILES) {
    const abs = path.join(root, rel)
    if (!fs.existsSync(abs)) continue
    const text = fs.readFileSync(abs, 'utf8').replace(/\r\n?/g, '\n')
    const start = text.indexOf(BEGIN)
    if (start === -1) continue
    const end = text.indexOf(END, start)
    const current = end === -1 ? text.slice(start) : text.slice(start, end + END.length) + '\n'
    const platform = /^\[cds-guard\]$/m.test(current) ? 'gitlab' : 'github'
    const flag = platform === 'gitlab' ? ' --platform gitlab' : ''
    found.push({ file: rel, platform, ok: current === block(config, platform, { file: rel }), hint: `npx @cbs-consulting/cds-guard codeowners${flag} --write ${rel}` })
  }
  const azure = path.join(root, DEFAULT_FILE.azure)
  if (fs.existsSync(azure)) {
    const text = fs.readFileSync(azure, 'utf8').replace(/\r\n?/g, '\n')
    const branch = (/^BRANCH=\$\{BRANCH:-(.*)\}$/m.exec(text) || [])[1]
    found.push({ file: DEFAULT_FILE.azure, platform: 'azure', ok: text === azureScript(config, { branch }), hint: `npx @cbs-consulting/cds-guard codeowners --platform azure --write${branch && branch !== 'main' ? ` --branch ${branch}` : ''}, then run ${DEFAULT_FILE.azure} again` })
  }
  return found.map(f => ({ ...f, file: toPosix(f.file) }))
}

module.exports = { block, azureScript, writeBlock, verify, PLATFORMS, DEFAULT_FILE, CODEOWNERS_FILES, BEGIN, END }
